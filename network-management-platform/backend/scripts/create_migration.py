if __name__ == "__main__":
    print("🚀 Network Management Platform - Migration Creator")
    print("=" * 60)
    
    if len(sys.argv) < 2:
        print("Usage:")
        print("  python scripts/create_migration.py <message>        # Auto-generate migration")
        print("  python scripts/create_migration.py -e <message>     # Create empty migration")
        print("\nExample:")
        print("  python scripts/create_migration.py 'Add user preferences table'")
        print("  python scripts/create_migration.py -e 'Custom data migration'")
        sys.exit(1)
    
    if sys.argv[1] == "-e" and len(sys.argv) > 2:
        # Create empty migration
        message = " ".join(sys.argv[2:])
        create_empty_migration(message)
    else:
        # Create autogenerated migration
        message = " ".join(sys.argv[1:])
        create_migration(message)